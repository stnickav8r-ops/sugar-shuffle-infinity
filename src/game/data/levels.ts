function norm(rows: string[]): string[] {
  const w = Math.max(...rows.map((r) => r.length));
  return rows.map((r) => r.padEnd(w, "."));
}

/** Pad empty sky so the floor sits at the bottom of the 720px camera. */
function tall(rows: string[], total = 15): string[] {
  const n = norm(rows);
  const pad = total - n.length;
  if (pad <= 0) return n;
  const empty = ".".repeat(n[0]!.length);
  return [...Array.from({ length: pad }, () => empty), ...n];
}

