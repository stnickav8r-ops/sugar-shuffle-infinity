export function worldSize(level: LevelDef) {
  return { w: level.rows[0]!.length * TILE, h: level.rows.length * TILE };
}

export function eachCell(level: LevelDef, fn: (ch: string, tx: number, ty: number) => void) {
  level.rows.forEach((row, ty) => {
    for (let tx = 0; tx < row.length; tx++) fn(row[tx] ?? ".", tx, ty);
  });
}

export function hubIdFor(floor: number) {
  return `hub-${Math.min(5, Math.max(1, floor))}`;
}
